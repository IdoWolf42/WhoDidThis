class TestFreeText:
    def test_gpt4_in_text(self, signal: MetadataSignal) -> None:
        content = "This document was produced using GPT-4 for summarization."
        result = signal.analyze(content)
        assert result is not None
        assert result.model_attribution == "OpenAI GPT-4"
        assert result.confidence == CONFIDENCE_FREE_TEXT
        assert result.evidence["source"] == "free_text"

    def test_gemini_in_text(self, signal: MetadataSignal) -> None:
        content = "The response was generated by Gemini Pro."
        result = signal.analyze(content)
        assert result is not None
        assert result.model_attribution == "Google Gemini"

    def test_claude_in_text(self, signal: MetadataSignal) -> None:
        content = "Powered by Claude from Anthropic."
        result = signal.analyze(content)
        assert result is not None
        assert result.model_attribution == "Anthropic Claude"

    def test_mistral_in_text(self, signal: MetadataSignal) -> None:
        content = "Using Mistral-7B for local inference."
        result = signal.analyze(content)
        assert result is not None
        assert result.model_attribution == "Mistral AI"

    def test_case_insensitive(self, signal: MetadataSignal) -> None:
        content = "output from GEMINI-FLASH"
        result = signal.analyze(content)
        assert result is not None
        assert result.model_attribution == "Google Gemini"

    def test_matched_text_in_evidence(self, signal: MetadataSignal) -> None:
        content = "This text was produced by gpt-4o."
        result = signal.analyze(content)
        assert result is not None
        assert "matched_text" in result.evidence
        assert "gpt-4o" in result.evidence["matched_text"].lower()  # type: ignore[operator]


# ---------------------------------------------------------------------------
# No match — should return None
# ---------------------------------------------------------------------------


class TestNoMatch:
    def test_plain_human_text(self, signal: MetadataSignal) -> None:
        content = "The quick brown fox jumps over the lazy dog."
        result = signal.analyze(content)
        assert result is None

    def test_empty_string(self, signal: MetadataSignal) -> None:
        result = signal.analyze("")
        assert result is None

    def test_json_without_model_info(self, signal: MetadataSignal) -> None:
        content = json.dumps({"name": "Alice", "age": 30, "city": "Paris"})
        result = signal.analyze(content)
        assert result is None

    def test_json_with_non_string_values(self, signal: MetadataSignal) -> None:
        content = json.dumps({"count": 42, "active": True, "data": [1, 2, 3]})
        result = signal.analyze(content)
        assert result is None

    def test_non_json_string(self, signal: MetadataSignal) -> None:
        content = "not json at all {broken"
        result = signal.analyze(content)
        assert result is None

    def test_json_list_root(self, signal: MetadataSignal) -> None:
        """JSON root that is a list (not a dict) should fall through to free-text."""
        content = json.dumps(["a", "b", "c"])
        result = signal.analyze(content)
        assert result is None


