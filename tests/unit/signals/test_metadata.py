class TestSignalResultValidation:
    def test_result_confidence_in_range(self, signal: MetadataSignal) -> None:
        content = json.dumps({"model": "gpt-4"})
        result = signal.analyze(content)
        assert result is not None
        assert 0.0 <= result.confidence <= 1.0

    def test_result_has_evidence(self, signal: MetadataSignal) -> None:
        content = json.dumps({"model": "gpt-4"})
        result = signal.analyze(content)
        assert result is not None
        assert isinstance(result.evidence, dict)
        assert len(result.evidence) > 0
