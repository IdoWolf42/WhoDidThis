"""
Unit tests for MetadataSignal.

Tests cover:
- JSON metadata with trusted keys (highest confidence path)
- JSON metadata with non-trusted keys (medium confidence path)
- Free-text pattern matching (medium confidence path)
- Various model patterns (OpenAI, Anthropic, Google, Meta, Mistral)
- Content with no model-identifying information (should return None)
- Edge cases: empty string, non-JSON string, nested JSON
"""

from __future__ import annotations

import json

import pytest

from whodidthis.signals.metadata import (
    CONFIDENCE_FREE_TEXT,
    CONFIDENCE_METADATA_FIELD,
    MetadataSignal,
)


@pytest.fixture
def signal() -> MetadataSignal:
    return MetadataSignal()


# ---------------------------------------------------------------------------
# JSON metadata — trusted key path (highest confidence)
# ---------------------------------------------------------------------------


class TestJsonTrustedKey:
    def test_model_field_gpt4(self, signal: MetadataSignal) -> None:
        content = json.dumps({"model": "gpt-4", "choices": [{"text": "Hello"}]})
        result = signal.analyze(content)
        assert result is not None
        assert result.model_attribution == "OpenAI GPT-4"
        assert result.confidence == CONFIDENCE_METADATA_FIELD
        assert result.signal_name == "metadata"
        assert result.evidence["source"] == "json_metadata_field"
        assert result.evidence["key"] == "model"

    def test_model_field_gpt4o(self, signal: MetadataSignal) -> None:
        content = json.dumps({"model": "gpt-4o"})
